"""Wrap the compose alert rules in a PrometheusRule for the cluster.

One definition of the alerts, two deployment targets: the compose stack loads
deploy/compose/prometheus/rules/ithaca.yml directly, the Prometheus operator
needs the same groups inside a PrometheusRule object. Run by `make dashboards`.

Plain text indentation, no YAML library: a rules file is a block mapping, and
indenting every line under `spec:` keeps it, comments included, byte-for-byte.
"""

import pathlib

here = pathlib.Path(__file__).parent
src = here / "../../compose/prometheus/rules/ithaca.yml"
out = here / "prometheusrule.yaml"

body = "".join(("  " + line) if line.strip() else line for line in src.read_text().splitlines(keepends=True))
out.write_text(
    "# GENERATED by deploy/k8s/monitoring/gen_rules.py from\n"
    "# deploy/compose/prometheus/rules/ithaca.yml — edit that file, then `make dashboards`.\n"
    "apiVersion: monitoring.coreos.com/v1\n"
    "kind: PrometheusRule\n"
    "metadata:\n"
    "  name: ithaca\n"
    "spec:\n" + body
)
print(f"wrote {out.resolve().relative_to(pathlib.Path.cwd())}")
